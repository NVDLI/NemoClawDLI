#!/usr/bin/env bash
# push_pages.sh publishes the built client-side site to a PRIVATE GitLab Pages project.
#
# Pages is served from a SEPARATE, dedicated GitLab project that holds ONLY the built
# site plus a trivial `pages` job, keeping it independent of the source repo's own CI.
# This script builds public/ and pushes that artifact (no source) to it.
#
# One-time setup of the dedicated project (for example, a private Pages host URL):
# https://<pages-host>/<group>/<project>/
#   1. Create an empty GitLab project, e.g. <group>/agents-pages.
#   2. Settings > General > Visibility > Pages: "Only project members" (keeps it private).
#   3. Create a token with write_repository (Project Access Token or a PAT).
#
# Publish (re-run any time to update the live site):
#   GITLAB_TOKEN=<token> scripts/build/push_pages.sh https://<host>/<group>/<project>.git [branch]
#
# Example:
#   GITLAB_TOKEN=glpat-xxx scripts/build/push_pages.sh \
#     https://<git-host>/<group>/agents-pages.git
#
# branch defaults to the project default branch name passed as $2 (default: main). The
# generated pages job runs on the default branch, so push to whatever that project uses.
#
# Prerequisites on the machine that runs this: python3 (for the build) and git.
set -euo pipefail

REMOTE="${1:-}"
BRANCH="${2:-main}"
if [ -z "$REMOTE" ]; then
  echo "usage: GITLAB_TOKEN=<token> $0 <gitlab-remote-url> [branch]" >&2
  exit 2
fi
case "$REMOTE" in
  https://*) : ;;
  *) echo "push_pages: expected an https GitLab remote URL, got: $REMOTE" >&2; exit 2 ;;
esac

# task1 root (this script lives in task1/scripts/).
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
T1="$(cd "$HERE/.." && pwd)"

# Publication is the last moment the repository controls its own bytes, and a workstation may
# never have installed the hooks. Audit the complete source tree here so restricted details and
# ephemeral infrastructure identifiers cannot reach the served site through this path.
if ! python3 "$T1/scripts/validation/sensitive_content_audit.py"; then
  echo "push_pages: REFUSING PUBLISH - restricted or private operational content detected." >&2
  exit 1
fi

# Authenticate without logging the token. Prefer GITLAB_TOKEN; otherwise trust whatever
# credentials the remote URL already carries. GitLab accepts the oauth2:<token> form.
PUSH_REMOTE="$REMOTE"
if [ -n "${GITLAB_TOKEN:-}" ]; then
  host_path="${REMOTE#https://}"
  host_path="${host_path#*@}"          # strip any existing user:token@ prefix
  PUSH_REMOTE="https://oauth2:${GITLAB_TOKEN}@${host_path}"
fi
redact() { sed -E "s#oauth2:[^@]*@#oauth2:***@#g"; }

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT
REPO="$WORK/repo"

# 1. Get the target repo and put the working tree on the target branch's tip, so the new
#    commit fast-forwards (works even when the branch is protected; only force-push is
#    blocked there). Cover: existing branch, branch present only as origin/<branch>, a repo
#    whose HEAD points elsewhere, and a brand-new empty project.
if git clone -q "$PUSH_REMOTE" "$REPO" 2>/dev/null && [ -e "$REPO/.git" ]; then
  cd "$REPO"
  git checkout -q "$BRANCH" 2>/dev/null \
    || git checkout -q -b "$BRANCH" "origin/$BRANCH" 2>/dev/null \
    || git checkout -q --orphan "$BRANCH"
else
  mkdir -p "$REPO"; cd "$REPO"
  git init -q
  git checkout -q -b "$BRANCH" 2>/dev/null || git symbolic-ref HEAD "refs/heads/$BRANCH"
  git remote add origin "$PUSH_REMOTE"
fi

# 2. Replace tracked content with a fresh build (keep .git). Artifact only, no source.
git rm -rqf . >/dev/null 2>&1 || true
rm -rf public .gitlab-ci.yml
bash "$T1/scripts/build/build_pages.sh" "$REPO/public"
if ! python3 "$T1/scripts/validation/sensitive_content_audit.py" --root "$REPO/public"; then
  echo "push_pages: REFUSING PUBLISH - generated Pages content crossed the sensitive boundary." >&2
  exit 1
fi

# 3. The dedicated project's entire pipeline: one `pages` job that serves the prebuilt
#    site. GitLab serves the `public/` artifact of a job named `pages`.
cat > .gitlab-ci.yml <<'YAML'
# Generated by task1/scripts/build/push_pages.sh. This project holds ONLY the built
# client-side site (no course source). It exists so GitLab can serve the site on
# Pages without adding a `pages` job to the source repo's protected DLI pipeline.
#
# Pages stays PRIVATE via Settings > General > Visibility > Pages: "Only project members".
# If this instance needs runner tags for the job, add them under `tags:` below.
pages:
  stage: deploy
  script:
    - echo "Serving prebuilt public/ ($(find public -name '*.html' | wc -l) pages)"
  artifacts:
    paths:
      - public
  rules:
    - if: $CI_COMMIT_BRANCH == $CI_DEFAULT_BRANCH
YAML

# 4. Commit and push the artifact (fast-forward, no force).
STAMP="$(date -u +%Y-%m-%dT%H:%M:%SZ)"
PAGE_COUNT="$(find public -name '*.html' | wc -l | tr -d ' ')"
git add -A
if git diff --cached --quiet; then
  echo "push_pages: site unchanged since last publish; nothing to push."
  exit 0
fi
git -c user.name="pages-publish" -c user.email="pages-publish@local" \
    commit -q -m "Publish client-side site ${STAMP} (${PAGE_COUNT} pages)"
git push -q origin "HEAD:${BRANCH}" 2>&1 | redact

echo "push_pages: published ${PAGE_COUNT} pages to ${BRANCH}."
echo "push_pages: site serves at the project's Pages URL once the pipeline's pages job finishes."
echo "push_pages: on the first publish only, set Settings > General > Visibility > Pages to 'Only project members'."
